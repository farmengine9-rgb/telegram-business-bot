-- Telegram Business Bot PostgreSQL schema, migration v1.
-- Apply with scripts/migrate-postgres.js using a private DATABASE_URL.
-- All currency amounts remain in integer kobo. Do not reset existing tables.
CREATE TABLE IF NOT EXISTS customers (
 chat_id TEXT PRIMARY KEY, username TEXT NOT NULL DEFAULT '',
 first_name TEXT NOT NULL DEFAULT '',last_name TEXT NOT NULL DEFAULT '',
 human INTEGER NOT NULL DEFAULT 0 CHECK(human IN (0,1)),
 created_at TEXT NOT NULL,updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 chat_id TEXT NOT NULL,role TEXT NOT NULL,content TEXT NOT NULL,created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_messages_chat ON messages(chat_id,id);
CREATE TABLE IF NOT EXISTS products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL,description TEXT NOT NULL DEFAULT '',price TEXT NOT NULL DEFAULT '',
 active INTEGER NOT NULL DEFAULT 1,image_url TEXT NOT NULL DEFAULT '',created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 chat_id TEXT NOT NULL,product TEXT NOT NULL,quantity INTEGER NOT NULL DEFAULT 1,
 status TEXT NOT NULL DEFAULT 'pending',notes TEXT NOT NULL DEFAULT '',created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY,value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS order_drafts (
 chat_id TEXT PRIMARY KEY,step TEXT NOT NULL,product TEXT NOT NULL DEFAULT '',
 quantity INTEGER NOT NULL DEFAULT 1,customer_name TEXT NOT NULL DEFAULT '',
 phone TEXT NOT NULL DEFAULT '',address TEXT NOT NULL DEFAULT '',
 notes TEXT NOT NULL DEFAULT '',updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS processed_updates (
 update_id BIGINT PRIMARY KEY,created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS inventory (
 product_id BIGINT PRIMARY KEY REFERENCES products(id) ON DELETE CASCADE,
 quantity INTEGER NOT NULL DEFAULT 0 CHECK(quantity>=0),
 reorder_level INTEGER NOT NULL DEFAULT 5 CHECK(reorder_level>=0),
 updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS stock_movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id BIGINT NOT NULL,delta INTEGER NOT NULL,reason TEXT NOT NULL,created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS payments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL,reference TEXT NOT NULL UNIQUE,email TEXT NOT NULL,
 amount_kobo BIGINT NOT NULL CHECK(amount_kobo>0),currency TEXT NOT NULL DEFAULT 'NGN',
 status TEXT NOT NULL DEFAULT 'pending',authorization_url TEXT NOT NULL DEFAULT '',
 created_at TEXT NOT NULL,verified_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_payments_order ON payments(order_id);
CREATE TABLE IF NOT EXISTS followups (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 chat_id TEXT NOT NULL,message TEXT NOT NULL,status TEXT NOT NULL DEFAULT 'draft',
 created_at TEXT NOT NULL,sent_at TEXT
);
CREATE TABLE IF NOT EXISTS consent (
 chat_id TEXT PRIMARY KEY,opted_in INTEGER NOT NULL DEFAULT 0 CHECK(opted_in IN (0,1)),
 updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS pos_sales (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 receipt TEXT UNIQUE NOT NULL,customer_name TEXT NOT NULL DEFAULT '',
 payment_method TEXT NOT NULL,payment_status TEXT NOT NULL,
 subtotal_kobo BIGINT NOT NULL,discount_kobo BIGINT NOT NULL DEFAULT 0,
 total_kobo BIGINT NOT NULL,tendered_kobo BIGINT,
 created_at TEXT NOT NULL,completed_at TEXT
);
CREATE TABLE IF NOT EXISTS pos_sale_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sale_id BIGINT NOT NULL REFERENCES pos_sales(id) ON DELETE CASCADE,
 product_id BIGINT NOT NULL,product_name TEXT NOT NULL,
 quantity INTEGER NOT NULL,unit_kobo BIGINT NOT NULL,line_kobo BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_pos_items_sale ON pos_sale_items(sale_id);
